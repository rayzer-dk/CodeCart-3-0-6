#!/usr/bin/env python3
"""Rebuild the storefront Font Awesome Core WOFF2 subsets from the bundled Free 7.x fonts.

Requires: pip install fonttools[woff] brotli
Usage: python tools/build_fontawesome_core.py
"""
import json
import re
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "upload/catalog/view/javascript/font-awesome"
MANIFEST = ROOT / "upload/system/config/codecart_fontawesome_core_manifest.json"
CSS = BASE / "css/font-awesome.min.css"
CORE_CSS = BASE / "css/font-awesome-core.min.css"

def icon_codes(css, names):
    codes = set()
    class_re = re.compile(r"\.fa-([a-z0-9][a-z0-9-]*)")
    for selector, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        if not names.intersection(class_re.findall(selector)):
            continue
        for value in re.findall(r"--fa\s*:\s*['\"]?\\([0-9a-fA-F]{2,6})", body):
            codes.add(int(value, 16))
    return codes

def build():
    manifest = json.loads(MANIFEST.read_text("utf-8"))
    assert manifest["format"] == 2
    css = CSS.read_text("utf-8")
    assert "Font Awesome Free 7.3.1" in css, "Expected upstream Free 7.3.1 CSS"
    names = set(manifest["core_supported_names"]) | set(manifest["core_icons"]) | set(manifest["manual_extra_icons"])
    codepoints = icon_codes(css, names)
    # Retain code points used by older OpenCart HTML entities and legacy components.
    codepoints.update(int(c, 16) for c in re.findall(
        r"['\"]([0-9a-fA-F]{4,6})['\"]",
        (ROOT / "upload/system/library/codecart/src/FontAwesomeManager.php").read_text("utf-8").split("private const SUPPORTED_LEGACY_CODES =", 1)[-1].split(";", 1)[0]
    ))
    codepoints.update(range(32, 127))
    assert len(codepoints) >= 100, "Core glyph list unexpectedly small"
    report = {}
    for style in ("solid-900", "regular-400", "brands-400"):
        source = BASE / "webfonts" / ("fa-" + style + ".woff2")
        target = BASE / "webfonts" / ("fa-" + style + "-core.woff2")
        font = TTFont(source)
        available = set(font.getBestCmap().keys())
        chosen = available.intersection(codepoints)
        assert len(chosen) >= 5, f"No glyphs selected for {style}"
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.recalc_bounds = True
        sub = subset.Subsetter(options=opts)
        sub.populate(unicodes=chosen)
        sub.subset(font)
        font.flavor = "woff2"
        font.save(target)
        report[style] = {"selected":len(chosen),"bytes":target.stat().st_size}
        assert target.stat().st_size < source.stat().st_size, f"Core font not smaller for {style}"
    # Free 7 CSS contains standard icon declarations and official v4 mappings.
    # Keep these mappings intact, replacing ONLY their webfont URLs.
    core_css = css
    for style in ("solid-900", "regular-400", "brands-400"):
        core_css = core_css.replace("fa-" + style + ".woff2", "fa-" + style + "-core.woff2")
    CORE_CSS.write_text("/*! CodeCart PRO Font Awesome Core 7.3.1: subset WOFF2, official Free v4 mappings. */\n" + core_css, "utf-8")
    # Build a fresh scanner inventory from the actual CSS, not stale 6.7.2 metadata.
    all_names = sorted(set(re.findall(r"\.fa-([a-z0-9][a-z0-9-]*)", css)))
    manifest["fontawesome_version"] = "7.3.1"
    manifest["description"] = "CodeCart PRO Font Awesome 7.3.1 Core/AUTO WOFF2 subsets; generated by tools/build_fontawesome_core.py."
    manifest["full_free_icons"] = all_names
    manifest["full_free_legacy_codes"] = sorted({format(n, "x") for n in icon_codes(css, all_names)})
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", "utf-8")
    print(json.dumps({"version":"7.3.1","core_icons":len(names),"full_names":len(all_names),"fonts":report}, indent=2))

if __name__ == "__main__":
    build()
