<?php
namespace CodeCart\Core;

/** External Cron URLs are HTTPS GET-only. Never execute user-provided shell commands. */
final class ExternalHttpTask {
    private $config;

    public function __construct($registry) {
        $this->config = $registry->get('config');
    }

    public function parseCommand(string $command): array {
        $command = trim($command);
        if (strlen($command) > 4096 || strpos($command, "\n") !== false || strpos($command, "\r") !== false
            || strpos($command, '`') !== false || strpos($command, '$(') !== false
            || strpos($command, ';') !== false || strpos($command, '|') !== false) {
            throw new \InvalidArgumentException('Invalid command syntax. Paste one curl/wget HTTPS request only.');
        }
        if (!preg_match('~^(?:(?:/usr/bin/|/bin/))?(?:curl|wget)\s+~i', $command)) {
            throw new \InvalidArgumentException('Use an HTTPS curl/wget GET command, not a shell script.');
        }
        if (!preg_match('~https://[^\s"\'<>]+~i', $command, $m)) {
            throw new \InvalidArgumentException('HTTPS URL not found in command.');
        }
        $url = $m[0];
        // Commands generated by the third-party module use a header, never a query secret.
        if (!preg_match('~(?:--header|-H)\s*(?:=\s*)?(["\'])(X-ACP-Cron-Key\s*:\s*[^"\']{8,512})\1~i', $command, $header)) {
            throw new \InvalidArgumentException('Missing X-ACP-Cron-Key header.');
        }
        $parts = explode(':', $header[2], 2);
        $secret = trim((string)($parts[1] ?? ''));
        if ($secret === '' || preg_match('/[\x00-\x1F\x7F]/', $secret)) {
            throw new \InvalidArgumentException('Invalid Cron authentication key.');
        }
        $this->validateUrl($url);
        return array('url' => $url, 'secret' => $secret);
    }

    private function validateUrl(string $url): string {
        $parts = parse_url($url);
        if (!is_array($parts) || ($parts['scheme'] ?? '') !== 'https'
            || !isset($parts['host']) || isset($parts['user']) || isset($parts['pass'])
            || isset($parts['port']) || isset($parts['fragment']) || strlen($url) > 1024) {
            throw new \InvalidArgumentException('Only standard HTTPS URLs without embedded credentials are accepted.');
        }
        $host = strtolower($parts['host']);
        if (!preg_match('/^(?=.{4,253}$)[a-z0-9][a-z0-9.-]*[a-z0-9]$/', $host)
            || strpos($host, '.') === false || filter_var($host, FILTER_VALIDATE_IP)) {
            throw new \InvalidArgumentException('Invalid public HTTPS hostname.');
        }
        $path = $parts['path'] ?? '';
        $query = array();
        parse_str($parts['query'] ?? '', $query);
        // Restrict to a purpose-built Cron endpoint, not arbitrary storefront actions.
        $route = (string)($query['route'] ?? '');
        if ($path !== '/index.php' || !preg_match('~^(?:extension/module/[a-z0-9_]+|cron/[a-z0-9_]+)/cron$~i', $route)) {
            throw new \InvalidArgumentException('Only an extension/module/.../cron endpoint is supported.');
        }
        foreach ($query as $key => $value) {
            if (!is_string($value) || preg_match('/(?:key|token|password|secret|auth)/i', $key)) {
                throw new \InvalidArgumentException('Never include secrets in the URL.');
            }
        }
        return $host;
    }

    private function encryptionKey(): string {
        $secret = (string)$this->config->get('config_encryption');
        if (strlen($secret) < 16 || !function_exists('openssl_encrypt')) {
            throw new \RuntimeException('Server encryption configuration is unavailable.');
        }
        return hash('sha256', 'codecart-http-cron-v1:' . $secret . ':' . DB_DATABASE, true);
    }

    public function protect(string $secret): string {
        $nonce = random_bytes(12);
        $tag = '';
        $encrypted = openssl_encrypt($secret, 'aes-256-gcm', $this->encryptionKey(), OPENSSL_RAW_DATA, $nonce, $tag);
        if ($encrypted === false) { throw new \RuntimeException('Failed to protect Cron key.'); }
        return base64_encode($nonce . $tag . $encrypted);
    }

    private function unprotect(string $value): string {
        $raw = base64_decode($value, true);
        if ($raw === false || strlen($raw) < 29) { throw new \RuntimeException('Invalid protected Cron key.'); }
        $secret = openssl_decrypt(substr($raw, 28), 'aes-256-gcm', $this->encryptionKey(), OPENSSL_RAW_DATA, substr($raw, 0, 12), substr($raw, 12, 16));
        if (!is_string($secret) || $secret === '') { throw new \RuntimeException('Unable to read protected Cron key.'); }
        return $secret;
    }

    private function publicIPv4(string $host): string {
        $ips = gethostbynamel($host);
        if (!$ips) { throw new \RuntimeException('HTTPS hostname has no public IPv4 address.'); }
        foreach ($ips as $ip) {
            if (filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4 | FILTER_FLAG_NO_PRIV_RANGE | FILTER_FLAG_NO_RES_RANGE)) {
                return $ip;
            }
        }
        throw new \RuntimeException('Private or reserved destination addresses are blocked.');
    }

    public function execute(array $args): array {
        if (!extension_loaded('curl')) { throw new \RuntimeException('PHP curl extension is unavailable.'); }
        $url = (string)($args['url'] ?? '');
        $host = $this->validateUrl($url);
        $ip = $this->publicIPv4($host);
        $secret = $this->unprotect((string)($args['key_enc'] ?? ''));
        $curl = curl_init($url);
        if (!$curl) { throw new \RuntimeException('Cannot initialize HTTPS request.'); }
        try {
            curl_setopt_array($curl, array(
                CURLOPT_RETURNTRANSFER => true,
                CURLOPT_HEADER => false,
                CURLOPT_FOLLOWLOCATION => false,
                CURLOPT_MAXREDIRS => 0,
                CURLOPT_CONNECTTIMEOUT => 7,
                CURLOPT_TIMEOUT => 25,
                CURLOPT_HTTPGET => true,
                CURLOPT_SSL_VERIFYPEER => true,
                CURLOPT_SSL_VERIFYHOST => 2,
                CURLOPT_IPRESOLVE => CURL_IPRESOLVE_V4,
                CURLOPT_RESOLVE => array($host . ':443:' . $ip),
                CURLOPT_PROXY => '',
                CURLOPT_HTTPHEADER => array('X-ACP-Cron-Key: ' . $secret),
                CURLOPT_USERAGENT => 'CodeCartCron/3.0.6',
                CURLOPT_NOSIGNAL => true
            ));
            $reply = curl_exec($curl);
            $status = (int)curl_getinfo($curl, CURLINFO_RESPONSE_CODE);
            if ($reply === false || $status < 200 || $status >= 300) {
                throw new \RuntimeException('External Cron request failed (HTTP ' . $status . ').');
            }
            return array('success' => true, 'message' => 'HTTPS endpoint accepted the request (HTTP ' . $status . '); extension action not independently verified.');
        } finally { curl_close($curl); }
    }
}
